def get_reply(text, language):
    text_lower = text.lower()

    if language == "Kannada":

        # Mandya
        if "ಮಂಡ್ಯ" in text or "mandya" in text_lower:
            return "ನಮಸ್ಕಾರ ರೈತರೆ. ನೀವು ಮಂಡ್ಯ ಜಿಲ್ಲೆಯಿಂದ ಮಾತನಾಡುತ್ತಿದ್ದೀರಿ ಎಂದು ನಾನು ಗುರುತಿಸಿದ್ದೇನೆ. ಮಂಡ್ಯದಲ್ಲಿ ಅಕ್ಕಿ, ಕಬ್ಬು ಮತ್ತು ರಾಗಿ ಬೆಳೆಗಳಿಗೆ ಸೂಕ್ತ ಮಾರ್ಗದರ್ಶನ ನೀಡಲು ನಾನು ಸಿದ್ಧನಿದ್ದೇನೆ. ದಯವಿಟ್ಟು ನಿಮ್ಮ ಬೆಳೆ ಅಥವಾ ಸಮಸ್ಯೆಯನ್ನು ಹೇಳಿ."

        # Chikkamagaluru
        elif "ಚಿಕ್ಕಮಗಳೂರು" in text or "ಚಿಕ್ಕಮಗಳೂರ" in text or "chikkamagaluru" in text_lower:
            return "ನಮಸ್ಕಾರ ರೈತರೆ. ನೀವು ಚಿಕ್ಕಮಗಳೂರು ಜಿಲ್ಲೆಯಿಂದ ಮಾತನಾಡುತ್ತಿದ್ದೀರಿ ಎಂದು ನಾನು ಗುರುತಿಸಿದ್ದೇನೆ. ಚಿಕ್ಕಮಗಳೂರಿನಲ್ಲಿ ಕಾಫಿ, ಮೆಣಸು ಮತ್ತು ಅಡಿಕೆ ಬೆಳೆಗಳು ಸಾಮಾನ್ಯವಾಗಿವೆ. ನಿಮ್ಮ ಬೆಳೆ ಅಥವಾ ಸಮಸ್ಯೆಯನ್ನು ತಿಳಿಸಿ, ನಾನು ಸಹಾಯ ಮಾಡುತ್ತೇನೆ."

        else:
            return "ನಮಸ್ಕಾರ ರೈತರೆ. ನಾನು ನಿಮ್ಮ ಕೃಷಿ ಸಹಾಯಕನು. ದಯವಿಟ್ಟು ನಿಮ್ಮ ಗ್ರಾಮ, ಬೆಳೆ ಅಥವಾ ಸಮಸ್ಯೆಯನ್ನು ತಿಳಿಸಿ."

    elif language == "Tamil":
        return "வணக்கம் விவசாயி அவர்களே. உங்கள் கிராமம், பயிர் அல்லது பிரச்சினையை சொல்லுங்கள்."

    elif language == "Telugu":
        return "నమస్కారం రైతు గారూ. మీ గ్రామం, పంట లేదా సమస్యను చెప్పండి."

    elif language == "Malayalam":
        return "നമസ്കാരം കർഷക സുഹൃത്തേ. നിങ്ങളുടെ ഗ്രാമം, വിള അല്ലെങ്കിൽ പ്രശ്നം പറയൂ."

    elif language == "Hindi":
        return "नमस्कार किसान जी। कृपया अपना गाँव, फसल या समस्या बताइए।"

    elif language == "Marathi":
        return "नमस्कार शेतकरी मित्रा. कृपया तुमचे गाव, पीक किंवा समस्या सांगा."

    elif language == "Tulu":
        return "ನಮಸ್ಕಾರ ರೈತರೆ. ನಿನ್ನ ಊರು, ಬೆಳೆ ಅಥವಾ ತೊಂದರೆ ಪಂಡುಲೆ."

    elif language == "Konkani":
        return "नमस्कार शेतकरी मित्रा. तुमचें गांव, पिक वा समस्या सांगा."

    else:
        return "Hello farmer. Please tell your village, crop, or problem."